<?php
// Металочерепиця заводу «Тайл» — таблиці допустимих довжин виробника (18 модулів, хвиля 350).
// «Класика», «Ретро»: завершений лист 500, 850, 1200… (350·n + 150), виготовляється до +220 (720),
//   не виготовляється 730–840 → записано 721–849.
// «Преміум», «Елегант», «Престиж», «Модерн»: завершений 420, 770, 1120… (350·n + 70), виготовляється до +280 (700),
//   не виготовляється 710–760 → записано 701–769.
// Ті самі дані у фронтенді — src/components/catalog/factoryTables.ts.
$mk = function (int $base, int $rec, int $rows): array {
    $r = [];
    for ($n = 1; $n <= $rows; $n++) { $s = 350 * $n + $base; $r[] = [$s + $rec + 1, $s + 349]; }
    return $r;
};
return [
    ['match' => '/класи[кч]|classic|ретро|retro/iu', 'min_length' => 500, 'max_length' => 6670, 'forbidden_lengths' => $mk(150, 220, 18)],
    ['match' => '/прем[іи]ум|premium|елегант|элегант|elegant|престиж|prestige|модерн|modern/iu', 'min_length' => 420, 'max_length' => 6650, 'forbidden_lengths' => $mk(70, 280, 18)],
];
